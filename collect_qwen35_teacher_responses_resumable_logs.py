def eprint(*items: Any) -> None:
    print(*items, file=sys.stderr, flush=True)


def load_jsonl(path: str | Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    with open(path, "r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            text = line.strip()
            if not text:
                continue
            try:
                obj = json.loads(text)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON on line {line_no} of {path}: {exc}") from exc
            rows.append(obj)
    return rows


def atomic_write_json(path: str | Path, obj: Dict[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + f".tmp.{os.getpid()}")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
        f.write("\n")
    os.replace(tmp, path)


def output_path_for_index(output_dir: str | Path, index: int) -> Path:
    return Path(output_dir) / "records" / f"row_{index:05d}.json"


def shard_range(args: argparse.Namespace, n_rows: int) -> Tuple[int, int]:
    if args.start_idx is not None or args.end_idx is not None:
        start = 0 if args.start_idx is None else args.start_idx
        end = n_rows if args.end_idx is None else args.end_idx
    else:
        start = int(args.shard_idx) * int(args.shard_size)
        end = min(start + int(args.shard_size), n_rows)
    start = max(0, min(start, n_rows))
    end = max(start, min(end, n_rows))
    if args.limit is not None:
        end = min(end, start + args.limit)
    return start, end


def extract_final_label(text: str) -> Optional[str]:
    if not text:
        return None
    # Prefer bracketed final labels used in the prompt.
    matches = re.findall(r"\[\s*(SAT|UNSAT)\s*\]", text, flags=re.IGNORECASE)
    if matches:
        return matches[-1].upper()
    bare = re.findall(r"\b(UNSAT|SAT)\b", text, flags=re.IGNORECASE)
    if bare:
        return bare[-1].upper()
    return None


def normalize_label(label: Any) -> Optional[str]:
    if isinstance(label, bool):
        return "SAT" if label else "UNSAT"
    if label is None:
        return None
    s = str(label).strip().upper()
    if s in {"SAT", "TRUE", "SATISFIABLE"}:
        return "SAT"
    if s in {"UNSAT", "FALSE", "UNSATISFIABLE"}:
        return "UNSAT"
    return None


def get_ground_truth_label(row: Dict[str, Any]) -> Optional[str]:
    for key in ("label", "satisfiable"):
        if key in row:
            lab = normalize_label(row.get(key))
            if lab:
                return lab
    gt = row.get("ground_truth")
    if isinstance(gt, dict):
        for key in ("label", "satisfiable"):
            if key in gt:
                lab = normalize_label(gt.get(key))
                if lab:
                    return lab
    return None


def choose_torch_dtype(dtype_name: str):
    import torch
    if dtype_name == "auto":
        return "auto"
    if dtype_name == "float16":
        return torch.float16
    if dtype_name == "bfloat16":
        return torch.bfloat16
    if dtype_name == "float32":
        return torch.float32
    raise ValueError(f"Unsupported dtype: {dtype_name}")


def set_seed(seed: int) -> None:
    import random
    import numpy as np
    import torch
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def get_enable_thinking_value(args: argparse.Namespace) -> Optional[bool]:
    if args.enable_thinking:
        return True
    if args.disable_thinking:
        return False
    return None


