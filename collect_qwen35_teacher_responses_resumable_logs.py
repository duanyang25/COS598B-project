def read_json_if_possible(path: Path) -> Optional[Dict[str, Any]]:
    try:
        with open(path, "r", encoding="utf-8") as f:
            obj = json.load(f)
        return obj if isinstance(obj, dict) else None
    except Exception:
        return None


def is_successful_record(path: Path, args: argparse.Namespace) -> bool:
    """Return True iff this row should be skipped during resumption.

    By default, only non-error records with a non-empty teacher response are
    considered complete. Error records, corrupted files, and likely-truncated
    records are treated as pending so a rerun will retry them.
    """
    if not path.exists():
        return False
    rec = read_json_if_possible(path)
    if rec is None:
        return False
    if rec.get("error"):
        return bool(args.skip_error_records)
    response = rec.get("teacher_response")
    if not isinstance(response, str) or not response.strip():
        return False
    gen_info = rec.get("generation_info")
    if isinstance(gen_info, dict) and gen_info.get("likely_truncated_by_max_new_tokens"):
        return not bool(args.retry_truncated_records)
    return True


def pending_rows_for_range(
    rows: Sequence[Dict[str, Any]],
    start: int,
    end: int,
    args: argparse.Namespace,
) -> Tuple[List[Tuple[int, Dict[str, Any]]], List[int]]:
    selected = list(enumerate(rows[start:end], start=start))
    if args.overwrite:
        return selected, []
    pending: List[Tuple[int, Dict[str, Any]]] = []
    complete: List[int] = []
    for i, row in selected:
        path = output_path_for_index(args.output_dir, i)
        if is_successful_record(path, args):
            complete.append(i)
        else:
            pending.append((i, row))
    return pending, complete


