#!/usr/bin/env python3
"""
Collect teacher responses for SATBench prompt JSONL files with Hugging Face
Transformers. Designed for Princeton/Slurm array jobs.

Input by default:
    dataset/satbench_teacher_prompts.jsonl

Output by default:
    teacher_responses_qwen35_2b/records/row_00000.json
    teacher_responses_qwen35_2b/records/row_00001.json
    ...

Key features:
  * One output JSON per prompt row, written atomically.
  * Slurm-array sharding: 210 jobs * 10 rows = 2100 rows.
  * Resumption: within a shard, successful existing rows are skipped. Missing,
    corrupted, empty, error, or incomplete records are regenerated.
  * Combine mode: merges per-row JSON records into full JSONL and SFT JSONL.
  * Status mode: reports which rows are complete/incomplete/missing.

Typical full-run command inside a Slurm array task:
    python collect_qwen35_teacher_responses_resumable.py \
      --mode generate \
      --prompts dataset/satbench_teacher_prompts.jsonl \
      --output_dir teacher_responses_qwen35_2b \
      --model_id Qwen/Qwen3.5-2B \
      --local_files_only \
      --shard_idx ${SLURM_ARRAY_TASK_ID} \
      --shard_size 10
"""

