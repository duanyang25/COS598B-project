def render_prompt_from_messages(
    tokenizer: Any,
    messages: Sequence[Dict[str, str]],
    enable_thinking: Optional[bool],
) -> str:
    if hasattr(tokenizer, "apply_chat_template"):
        kwargs: Dict[str, Any] = {"tokenize": False, "add_generation_prompt": True}
        if enable_thinking is not None:
            kwargs["enable_thinking"] = enable_thinking
        try:
            return tokenizer.apply_chat_template(messages, **kwargs)
        except TypeError:
            kwargs.pop("enable_thinking", None)
            return tokenizer.apply_chat_template(messages, **kwargs)

    chunks: List[str] = []
    for msg in messages:
        role = msg.get("role", "user")
        content = msg.get("content", "")
        chunks.append(f"{role.upper()}:\n{content}")
    chunks.append("ASSISTANT:\n")
    return "\n\n".join(chunks)


def load_model_and_tokenizer(args: argparse.Namespace):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    eprint(f"Loading tokenizer: {args.model_id}")
    tokenizer = AutoTokenizer.from_pretrained(
        args.model_id,
        trust_remote_code=args.trust_remote_code,
        local_files_only=args.local_files_only,
    )
    if tokenizer.pad_token_id is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"

    model_kwargs: Dict[str, Any] = {
        "trust_remote_code": args.trust_remote_code,
        "local_files_only": args.local_files_only,
        "torch_dtype": choose_torch_dtype(args.dtype),
    }
    if args.device_map and args.device_map != "none" and args.device_map != "cuda":
        model_kwargs["device_map"] = args.device_map
    if args.attn_implementation:
        model_kwargs["attn_implementation"] = args.attn_implementation

    eprint(f"Loading model: {args.model_id}")
    model = AutoModelForCausalLM.from_pretrained(args.model_id, **model_kwargs)

    if args.device_map == "cuda":
        if not torch.cuda.is_available():
            raise RuntimeError("--device_map cuda requested but CUDA is not available.")
        model = model.to("cuda")

    model.eval()
    return model, tokenizer


def get_model_device(model: Any):
    import torch
    if hasattr(model, "hf_device_map") and isinstance(model.hf_device_map, dict):
        for dev in model.hf_device_map.values():
            if dev not in ("cpu", "disk", "meta"):
                return torch.device(dev)
    try:
        return next(model.parameters()).device
    except StopIteration:
        return torch.device("cuda:0" if torch.cuda.is_available() else "cpu")


def batch_iter(items: Sequence[Tuple[int, Dict[str, Any]]], batch_size: int) -> Iterable[List[Tuple[int, Dict[str, Any]]]]:
    for i in range(0, len(items), batch_size):
        yield list(items[i : i + batch_size])


def messages_from_row(row: Dict[str, Any]) -> List[Dict[str, str]]:
    messages = row.get("messages")
    if isinstance(messages, list) and messages:
        return messages
    fallback: List[Dict[str, str]] = []
    if row.get("system_prompt"):
        fallback.append({"role": "system", "content": str(row["system_prompt"])})
    fallback.append({"role": "user", "content": str(row.get("user_prompt", ""))})
    return fallback


def generate_for_batch(
    model: Any,
    tokenizer: Any,
    batch_rows: List[Tuple[int, Dict[str, Any]]],
    args: argparse.Namespace,
) -> List[Dict[str, Any]]:
    import torch

    enable_thinking = get_enable_thinking_value(args)
    prompts = [render_prompt_from_messages(tokenizer, messages_from_row(row), enable_thinking) for _, row in batch_rows]

    tok_kwargs: Dict[str, Any] = {"return_tensors": "pt", "padding": True}
    if args.max_input_tokens and args.max_input_tokens > 0:
        tok_kwargs.update({"truncation": True, "max_length": args.max_input_tokens})

    inputs = tokenizer(prompts, **tok_kwargs)
    input_token_counts = [int(x) for x in inputs["attention_mask"].sum(dim=1).tolist()]
    padded_input_len = int(inputs["input_ids"].shape[1])

    device = get_model_device(model)
    inputs = {k: v.to(device) for k, v in inputs.items()}

    gen_kwargs: Dict[str, Any] = {
        "max_new_tokens": args.max_new_tokens,
        "do_sample": args.do_sample,
        "repetition_penalty": args.repetition_penalty,
        "pad_token_id": tokenizer.pad_token_id,
        "eos_token_id": tokenizer.eos_token_id,
    }
    if args.do_sample:
        gen_kwargs.update({"temperature": args.temperature, "top_p": args.top_p, "top_k": args.top_k})

    start_time = time.time()
    with torch.inference_mode():
        outputs = model.generate(**inputs, **gen_kwargs)
    elapsed = time.time() - start_time

    batch_generated_total = 0
    decoded: List[Tuple[str, int, bool]] = []
    for i in range(outputs.shape[0]):
        new_ids_tensor = outputs[i, padded_input_len:]
        gen_ids = [int(t) for t in new_ids_tensor.tolist() if int(t) != tokenizer.pad_token_id]
        response = tokenizer.decode(gen_ids, skip_special_tokens=True).strip()
        gen_token_count = len(gen_ids)
        batch_generated_total += gen_token_count
        ended_with_eos = bool(gen_ids and tokenizer.eos_token_id is not None and gen_ids[-1] == tokenizer.eos_token_id)
        likely_truncated = gen_token_count >= args.max_new_tokens and not ended_with_eos
        decoded.append((response, gen_token_count, likely_truncated))

    results: List[Dict[str, Any]] = []
    for i, (row_index, row) in enumerate(batch_rows):
        response, gen_token_count, likely_truncated = decoded[i]
        teacher_label = extract_final_label(response)
        gt_label = get_ground_truth_label(row)

        result: Dict[str, Any] = {
            "index": row.get("index", row_index),
            "row_index_in_prompt_file": row_index,
            "prompt_id": row.get("prompt_id", f"row_{row_index:05d}"),
            "model_id": args.model_id,
            "teacher_response": response,
            "teacher_extracted_label": teacher_label,
            "ground_truth_label": gt_label,
            "teacher_label_matches_ground_truth": (
                teacher_label == gt_label if teacher_label is not None and gt_label is not None else None
            ),
            "generation_info": {
                "input_tokens": input_token_counts[i],
                "generated_tokens": gen_token_count,
                "batch_elapsed_seconds": elapsed,
                "tokens_per_second_for_batch": batch_generated_total / elapsed if elapsed > 0 else None,
                "likely_truncated_by_max_new_tokens": likely_truncated,
                "max_new_tokens": args.max_new_tokens,
                "do_sample": args.do_sample,
                "temperature": args.temperature if args.do_sample else None,
                "top_p": args.top_p if args.do_sample else None,
                "top_k": args.top_k if args.do_sample else None,
                "repetition_penalty": args.repetition_penalty,
                "enable_thinking": enable_thinking,
            },
            "created_at_unix": time.time(),
            "slurm_job_id": os.environ.get("SLURM_JOB_ID"),
            "slurm_array_job_id": os.environ.get("SLURM_ARRAY_JOB_ID"),
            "slurm_array_task_id": os.environ.get("SLURM_ARRAY_TASK_ID"),
            "hostname": os.uname().nodename if hasattr(os, "uname") else None,
        }

        if args.save_prompt:
            result["messages"] = row.get("messages")
            result["system_prompt"] = row.get("system_prompt")
            result["user_prompt"] = row.get("user_prompt")
        for key in ["label", "satisfiable", "certificate_type", "ground_truth"]:
            if key in row:
                result[key] = row[key]

        results.append(result)

    return results


