def prepare_output_dirs(output_dir: str | Path) -> None:
    Path(output_dir).mkdir(parents=True, exist_ok=True)
    (Path(output_dir) / "records").mkdir(parents=True, exist_ok=True)
    (Path(output_dir) / "logs").mkdir(parents=True, exist_ok=True)


def run_generate(args: argparse.Namespace) -> None:
    import torch

    prepare_output_dirs(args.output_dir)
    rows = load_jsonl(args.prompts)
    if args.expected_rows and len(rows) != args.expected_rows:
        raise ValueError(f"Expected {args.expected_rows} prompt rows, found {len(rows)} in {args.prompts}")

    n_rows = len(rows)
    start, end = shard_range(args, n_rows)
    pending, complete = pending_rows_for_range(rows, start, end, args)

    eprint(f"Loaded {n_rows} prompt rows from {args.prompts}")
    eprint(f"Shard idx={args.shard_idx}, shard_size={args.shard_size}; sub-range=[{start}, {end})")
    eprint(f"Resume scan: complete={len(complete)}, pending={len(pending)}, pending_rows={[i for i, _ in pending]}")

    shard_meta = {
        "model_id": args.model_id,
        "prompts": args.prompts,
        "output_dir": args.output_dir,
        "shard_idx": args.shard_idx,
        "shard_size": args.shard_size,
        "start": start,
        "end": end,
        "complete_rows_at_start": complete,
        "pending_rows_at_start": [i for i, _ in pending],
        "batch_size": args.batch_size,
        "max_new_tokens": args.max_new_tokens,
        "dtype": args.dtype,
        "device_map": args.device_map,
        "local_files_only": args.local_files_only,
        "slurm_job_id": os.environ.get("SLURM_JOB_ID"),
        "slurm_array_job_id": os.environ.get("SLURM_ARRAY_JOB_ID"),
        "slurm_array_task_id": os.environ.get("SLURM_ARRAY_TASK_ID"),
        "cuda_visible_devices": os.environ.get("CUDA_VISIBLE_DEVICES"),
        "hostname": os.uname().nodename if hasattr(os, "uname") else None,
    }
    atomic_write_json(Path(args.output_dir) / "logs" / f"shard_{int(args.shard_idx):05d}_meta.json", shard_meta)

    if not pending:
        eprint("Nothing to do for this shard. All rows are already complete.")
        return

    set_seed(args.seed + int(args.shard_idx))
    load_start = time.time()
    model, tokenizer = load_model_and_tokenizer(args)
    load_elapsed = time.time() - load_start
    eprint(f"Model loaded in {load_elapsed:.2f} seconds")

    total_generated = 0
    total_prompt_tokens = 0
    done = 0
    failures = 0
    gen_start = time.time()

    for batch in batch_iter(pending, max(1, args.batch_size)):
        try:
            results = generate_for_batch(model, tokenizer, batch, args)
        except Exception as exc:
            failures += len(batch)
            err = "".join(traceback.format_exception(type(exc), exc, exc.__traceback__))
            eprint(f"ERROR while generating batch rows {[i for i, _ in batch]}:\n{err}")
            if args.save_error_records:
                for row_index, row in batch:
                    error_record = {
                        "index": row.get("index", row_index),
                        "row_index_in_prompt_file": row_index,
                        "prompt_id": row.get("prompt_id", f"row_{row_index:05d}"),
                        "model_id": args.model_id,
                        "error": str(exc),
                        "traceback": err,
                        "created_at_unix": time.time(),
                        "slurm_job_id": os.environ.get("SLURM_JOB_ID"),
                        "slurm_array_task_id": os.environ.get("SLURM_ARRAY_TASK_ID"),
                    }
                    if args.save_prompt:
                        error_record["messages"] = row.get("messages")
                    atomic_write_json(output_path_for_index(args.output_dir, row_index), error_record)
            continue

        for result in results:
            row_index = int(result["row_index_in_prompt_file"])
            atomic_write_json(output_path_for_index(args.output_dir, row_index), result)
            total_generated += int(result["generation_info"].get("generated_tokens") or 0)
            total_prompt_tokens += int(result["generation_info"].get("input_tokens") or 0)
            done += 1
            eprint(f"Wrote row {row_index} -> {output_path_for_index(args.output_dir, row_index)}")

        if done % max(1, args.log_every) == 0 or done == len(pending):
            elapsed = time.time() - gen_start
            tok_s = total_generated / elapsed if elapsed > 0 else 0.0
            eprint(f"Progress shard {args.shard_idx}: newly_completed={done}/{len(pending)}, failures={failures}, gen_tok/s={tok_s:.2f}")
            if torch.cuda.is_available():
                try:
                    eprint(
                        f"CUDA max allocated={torch.cuda.max_memory_allocated()/(1024**3):.2f} GiB, "
                        f"max reserved={torch.cuda.max_memory_reserved()/(1024**3):.2f} GiB"
                    )
                except Exception:
                    pass

    total_elapsed = time.time() - gen_start
    # Re-scan at the end so the summary reflects resumable state.
    pending_after, complete_after = pending_rows_for_range(rows, start, end, args)
    summary = {
        "model_id": args.model_id,
        "prompts": args.prompts,
        "output_dir": args.output_dir,
        "shard_idx": args.shard_idx,
        "shard_size": args.shard_size,
        "start": start,
        "end": end,
        "rows_completed_this_run": done,
        "failures_this_run": failures,
        "complete_rows_after_run": complete_after,
        "pending_rows_after_run": [i for i, _ in pending_after],
        "total_generated_tokens_this_run": total_generated,
        "total_prompt_tokens_this_run": total_prompt_tokens,
        "load_seconds": load_elapsed,
        "generation_seconds": total_elapsed,
        "generated_tokens_per_second": total_generated / total_elapsed if total_elapsed > 0 else None,
        "rows_per_hour": done / total_elapsed * 3600 if total_elapsed > 0 else None,
        "slurm_job_id": os.environ.get("SLURM_JOB_ID"),
        "slurm_array_job_id": os.environ.get("SLURM_ARRAY_JOB_ID"),
        "slurm_array_task_id": os.environ.get("SLURM_ARRAY_TASK_ID"),
        "cuda_visible_devices": os.environ.get("CUDA_VISIBLE_DEVICES"),
        "hostname": os.uname().nodename if hasattr(os, "uname") else None,
    }
    atomic_write_json(Path(args.output_dir) / "logs" / f"shard_{int(args.shard_idx):05d}_summary.json", summary)
    eprint("SUMMARY " + json.dumps(summary, ensure_ascii=False))


def run_inspect(args: argparse.Namespace) -> None:
    rows = load_jsonl(args.prompts)
    print(f"Loaded {len(rows)} rows from {args.prompts}")
    if args.expected_rows and len(rows) != args.expected_rows:
        print(f"WARNING: expected {args.expected_rows} rows")
    if not rows:
        return
    first = rows[0]
    print("First row keys:", sorted(first.keys()))
    print("First row prompt_id:", first.get("prompt_id"))
    print("First row label:", first.get("label"))
    messages = first.get("messages")
    if isinstance(messages, list):
        print("messages roles:", [m.get("role") for m in messages])
        for m in messages:
            role = m.get("role")
            content = str(m.get("content", ""))
            print(f"--- {role} content preview ---")
            print(content[:1200])
            print()


def iter_record_files(output_dir: str | Path) -> Iterable[Path]:
    records_dir = Path(output_dir) / "records"
    if not records_dir.exists():
        return []
    return sorted(records_dir.glob("row_*.json"))


def run_status(args: argparse.Namespace) -> None:
    rows = load_jsonl(args.prompts)
    if args.expected_rows and len(rows) != args.expected_rows:
        print(f"WARNING: expected {args.expected_rows} prompt rows, found {len(rows)}")
    complete: List[int] = []
    missing_or_incomplete: List[int] = []
    errors: List[int] = []
    truncated: List[int] = []
    for i in range(len(rows)):
        path = output_path_for_index(args.output_dir, i)
        rec = read_json_if_possible(path)
        if rec is None:
            missing_or_incomplete.append(i)
            continue
        if rec.get("error"):
            errors.append(i)
            if not args.skip_error_records:
                missing_or_incomplete.append(i)
            else:
                complete.append(i)
            continue
        gen = rec.get("generation_info")
        if isinstance(gen, dict) and gen.get("likely_truncated_by_max_new_tokens"):
            truncated.append(i)
            if args.retry_truncated_records:
                missing_or_incomplete.append(i)
            else:
                complete.append(i)
            continue
        if isinstance(rec.get("teacher_response"), str) and rec["teacher_response"].strip():
            complete.append(i)
        else:
            missing_or_incomplete.append(i)

    summary = {
        "prompts": args.prompts,
        "output_dir": args.output_dir,
        "n_prompt_rows": len(rows),
        "n_complete": len(complete),
        "n_missing_or_incomplete": len(missing_or_incomplete),
        "n_error_records": len(errors),
        "n_likely_truncated_records": len(truncated),
        "first_missing_or_incomplete": missing_or_incomplete[:50],
        "first_error_records": errors[:50],
        "first_truncated_records": truncated[:50],
    }
    print("STATUS " + json.dumps(summary, ensure_ascii=False, indent=2))


def run_combine(args: argparse.Namespace) -> None:
    files = list(iter_record_files(args.output_dir))
    if not files:
        raise FileNotFoundError(f"No row_*.json files found under {Path(args.output_dir) / 'records'}")

    records: List[Dict[str, Any]] = []
    errors = 0
    for p in files:
        rec = read_json_if_possible(p)
        if rec is None:
            errors += 1
            continue
        if rec.get("error"):
            errors += 1
        records.append(rec)

    records.sort(key=lambda r: int(r.get("row_index_in_prompt_file", r.get("index", 10**12))))

    combined_path = Path(args.combined_out)
    if combined_path.parent != Path("."):
        combined_path.parent.mkdir(parents=True, exist_ok=True)
    with open(combined_path, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    sft_path = Path(args.sft_out)
    if sft_path.parent != Path("."):
        sft_path.parent.mkdir(parents=True, exist_ok=True)
    sft_count = 0
    with open(sft_path, "w", encoding="utf-8") as f:
        for rec in records:
            response = rec.get("teacher_response")
            if not response and not args.write_sft_all:
                continue
            messages = rec.get("messages")
            if not isinstance(messages, list):
                continue
            sft_obj = {
                "prompt_id": rec.get("prompt_id"),
                "index": rec.get("index"),
                "row_index_in_prompt_file": rec.get("row_index_in_prompt_file"),
                "model_id": rec.get("model_id"),
                "ground_truth_label": rec.get("ground_truth_label"),
                "teacher_extracted_label": rec.get("teacher_extracted_label"),
                "teacher_label_matches_ground_truth": rec.get("teacher_label_matches_ground_truth"),
                "messages": messages + [{"role": "assistant", "content": response or ""}],
            }
            if "ground_truth" in rec:
                sft_obj["ground_truth"] = rec["ground_truth"]
            f.write(json.dumps(sft_obj, ensure_ascii=False) + "\n")
            sft_count += 1

    summary = {
        "output_dir": args.output_dir,
        "n_record_files_read": len(files),
        "n_records_written": len(records),
        "n_error_or_corrupted_records": errors,
        "combined_out": str(combined_path),
        "sft_out": str(sft_path),
        "n_sft_rows": sft_count,
    }
    print("COMBINE_SUMMARY " + json.dumps(summary, ensure_ascii=False, indent=2))


def main() -> None:
    args = parse_args()
    if args.mode == "inspect":
        run_inspect(args)
    elif args.mode == "status":
        run_status(args)
    elif args.mode == "combine":
        run_combine(args)
    elif args.mode == "generate":
        run_generate(args)
    else:
        raise ValueError(args.mode)


if __name__ == "__main__":
    main()
